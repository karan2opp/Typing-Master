// Builds src/wordlists/en.ts and hi.ts: frequency-ranked lists of up to 10,000
// words each, used for random-word tests (top 200 / 1k / 5k / 10k = difficulty).
//
// Usage: node scripts/build-wordlists.mjs <sources-dir> [en|hi]
//
// Sources (see src/wordlists/README.md for licences):
//   en: Peter Norvig count_1w.txt (word counts), cleaned with the dwyl
//       words_alpha.txt dictionary, minus LDNOOBW bad words.
//   hi: Leipzig Corpora Collection, Hindi news 2020 + Wikipedia 2021 word lists.
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "wordlists");
const src = process.argv[2];
const only = process.argv[3];
if (!src) throw new Error("usage: node build-wordlists.mjs <sources-dir> [en|hi]");

const LIMIT = 10_000;
const lines = (file) => readFileSync(join(src, file), "utf8").split(/\r?\n/);

function write(name, words) {
  const text = words.join(" ");
  writeFileSync(
    join(out, `${name}.ts`),
    `// Generated by scripts/build-wordlists.mjs from the sources in README.md. Do not edit by hand.\n` +
      `// ${words.length} words, most frequent first.\n` +
      `export const ${name.toUpperCase()} = ${JSON.stringify(text)};\n`,
  );
  console.log(`${name}: wrote ${words.length} words (${(text.length / 1024).toFixed(0)} KB)`);
}

// ---- English ------------------------------------------------------------------

function buildEnglish() {
  const dictionary = new Set(lines("words_alpha.txt").map((w) => w.trim()));
  const bad = new Set(
    lines("bad-en.txt")
      .map((w) => w.trim().toLowerCase())
      .filter((w) => /^[a-z]+$/.test(w)),
  );
  // Real dictionary entries that are web or abbreviation noise at the top of a web corpus.
  const noise = new Set(
    "www http https com org net edu gov html php asp cgi url pdf jpg gif png usb dvd cnet gbp cd pc tv uk usa eur pm am ok ebay amazon google yahoo msn hotel hotels casino poker".split(
      " ",
    ),
  );
  // A school app avoids religious-identity words and the like; keep this list short and reviewable.
  const sensitive = new Set(
    "allah jesus christ christian christians muslim muslims islam islamic hindu hindus jewish jews catholic catholics bible quran sikh buddhist".split(
      " ",
    ),
  );
  // The only two-letter words (the dictionary also holds fragments such as "ic" and "ny").
  const twoLetter = new Set("of to in is it on by as at be or we an my he up so us no if me go do am oh ok".split(" "));
  const words = [];
  for (const line of lines("count_1w.txt")) {
    const word = line.split("\t")[0];
    if (!word || !/^[a-z]+$/.test(word)) continue;
    if (word.length > 14 || (word.length === 1 && word !== "a" && word !== "i")) continue;
    if (word.length === 2 && !twoLetter.has(word)) continue;
    if (word.length > 1 && !/[aeiouy]/.test(word)) continue; // "html", "www", "pdf"
    if (!dictionary.has(word) || bad.has(word) || noise.has(word) || sensitive.has(word)) continue;
    words.push(word);
    if (words.length === LIMIT) break;
  }
  write("en", words);
}

// ---- Hindi ---------------------------------------------------------------------

/** Every character the Inscript layout can type, read from the layout table itself. */
function inscriptChars() {
  const layouts = readFileSync(join(here, "..", "src", "layouts.ts"), "utf8");
  const table = layouts.slice(layouts.indexOf("const INSCRIPT"), layouts.indexOf("};", layouts.indexOf("const INSCRIPT")));
  const chars = new Set();
  for (const m of table.matchAll(/\["([^"]*)",\s*"([^"]*)"\]/g)) {
    for (const s of [m[1], m[2]]) for (const c of s) chars.add(c);
  }
  return chars;
}

// A Devanagari word: syllables of consonant clusters (+ nukta) with an optional vowel sign and
// nasal mark, or independent vowels. Rejects fragments such as a stray vowel sign or a trailing virama.
const CONSONANT = "[\\u0915-\\u0939]\\u093C?";
const SYLLABLE = `(?:${CONSONANT}(?:\\u094D${CONSONANT})*[\\u093E-\\u094C]?[\\u0901-\\u0903]?|[\\u0905-\\u0914\\u0960\\u0961][\\u0901-\\u0903]?)`;
const WORD = new RegExp(`^${SYLLABLE}+$`, "u");

// Words never offered to students. Whole-word matches only (a stem such as "लंड"
// would also catch the city of London). Have a Hindi speaker review this list.
const HINDI_BLOCKED = new Set(
  "चूतिया चूत गांड गांडू लंड लौड़ा लौडा रंडी रांड भोसड़ी भोसडी मादरचोद बहनचोद चोद चुदाई हरामी हरामज़ादा भड़वा भडवा कमीना कमीनी कुतिया छिनाल ठरकी झांट".split(
    " ",
  ),
);

function buildHindi() {
  const typeable = inscriptChars();
  const score = new Map();
  const roots = readdirSync(join(src, "leipzig")).filter((d) => !d.endsWith(".gz"));
  if (roots.length === 0) throw new Error("no extracted Leipzig corpora in " + join(src, "leipzig"));
  for (const root of roots) {
    const dir = join(src, "leipzig", root);
    const file = readdirSync(dir, { recursive: true }).find((f) => String(f).endsWith("-words.txt"));
    if (!file) throw new Error(`no *-words.txt in ${dir}`);
    const rows = readFileSync(join(dir, String(file)), "utf8")
      .split(/\r?\n/)
      .map((l) => l.split("\t"))
      .filter((r) => r.length >= 3);
    const total = rows.reduce((a, r) => a + Number(r[2]), 0);
    // Each corpus counts equally, so news names do not drown out everyday words.
    for (const [, raw, freq] of rows) {
      const word = raw.normalize("NFC");
      score.set(word, (score.get(word) ?? 0) + Number(freq) / total);
    }
    console.log(`hi: read ${rows.length} entries from ${root}`);
  }

  const words = [...score.entries()]
    .filter(([w]) => {
      const length = Array.from(w).length;
      return (
        length >= 2 &&
        length <= 14 &&
        WORD.test(w) &&
        Array.from(w).every((c) => typeable.has(c)) &&
        !HINDI_BLOCKED.has(w)
      );
    })
    .sort((a, b) => b[1] - a[1])
    .slice(0, LIMIT)
    .map(([w]) => w);
  write("hi", words);
}

if (only !== "hi") buildEnglish();
if (only !== "en") {
  if (existsSync(join(src, "leipzig"))) buildHindi();
  else console.log("hi: skipped (no leipzig sources yet)");
}
